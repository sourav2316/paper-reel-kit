export const createStrokes = (text: string, x: number, y: number, textScale = 1): Segment[] => {
  const strokes: Segment[] = [];
  const size = Math.min(60, 780 / (text.length * .74)) * textScale;
  let cursor = x;
  let tip: Point | undefined;
  for (const character of text.toUpperCase()) {
    for (const path of glyph[character] ?? []) {
      const points: Point[] = path.map(([u,v]) => [cursor + (u + .055 * (1-v)) * size * .67, y + v * size]);
      if (tip) append(tip, points[0], false);
      for (let i=1; i<points.length; i++) append(points[i-1], points[i], true);
      tip = points[points.length - 1];
    }
    cursor += size * (character === " " ? .47 : .74);
  }
  return strokes;

  function append(from: Point, to: Point, ink: boolean) {
    const length = Math.hypot(to[0]-from[0], to[1]-from[1]);
    if (length > 0) strokes.push({ from, to, length, ink });
  }
};
